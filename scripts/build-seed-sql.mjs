#!/usr/bin/env node
/**
 * Builds the one-time Supabase seed from data/seed.local.json (gitignored).
 *
 *   node scripts/build-seed-sql.mjs
 *
 * Writes:
 *   supabase/seed.local.sql       seed only (customers, account shells, history)
 *   supabase/RUN_ONCE.local.sql   migration + seed, to paste into the SQL Editor
 *
 * Both outputs are gitignored because they contain customer mobile numbers.
 * The seed is idempotent: existing mobiles, accounts and history rows are skipped.
 * Account cookies are NOT seeded: the old ones were exposed publicly, so each
 * account is created as "needs_reimport" and keeps its id so customer links survive.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const seedPath = path.join(root, 'data', 'seed.local.json');
const migrationPath = path.join(root, 'supabase', 'migrations', '20261006_tetra_v2.sql');

const seed = JSON.parse(fs.readFileSync(seedPath, 'utf8'));

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;
const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

function normMobile(raw) {
  const d = String(raw || '').replace(/\D/g, '');
  if (/^\d{10}$/.test(d)) return d;
  if (/^91\d{10}$/.test(d) || /^0\d{10}$/.test(d)) return d.slice(-10);
  return null;
}

const isoDate = (v) => (/^\d{4}-\d{2}-\d{2}$/.test(v || '') ? v : null);

const lines = ['-- One-time seed (generated by scripts/build-seed-sql.mjs). Safe to re-run.', 'begin;', ''];

const accounts = seed.netflixCookies || [];
for (const a of accounts) {
  lines.push(
    `insert into public.cookie_pool (id, profile_name, account_label, account_email, user_agent, cookies, status, last_detail)` +
      ` values (${q(a.id)}, ${q(a.profileName || 'Netflix Account')}, ${q(a.accountLabel)}, ${q(a.accountEmail)},` +
      ` ${lit(a.userAgent || '')}, '[]'::jsonb, 'needs_reimport',` +
      ` 'Seeded without cookies. The previous cookies were exposed publicly: sign this account out of all devices and import fresh cookies.')` +
      ` on conflict (id) do nothing;`
  );
}
lines.push('');

const seen = new Set();
let skipped = 0;
const history = [];
for (const c of seed.customers || []) {
  const mobile = normMobile(c.mobile);
  if (!mobile || seen.has(mobile)) {
    skipped++;
    continue;
  }
  seen.add(mobile);
  const accountId = accounts.some((a) => a.id === c.assignedAccountId) ? c.assignedAccountId : null;
  lines.push(
    `insert into public.subscribers (mobile, service, subscription_date, validity, expiry_date, assigned_account_id, is_blocked, created_at)` +
      ` values (${q(mobile)}, ${q(c.service || 'Netflix')}, ${q(isoDate(c.subscriptionDate))}, ${q(c.validity || '1 Month')},` +
      ` ${q(isoDate(c.expiryDate))}, ${q(accountId)}, ${c.isBlocked ? 'true' : 'false'}, ${q(c.createdAt || new Date().toISOString())})` +
      ` on conflict (mobile) do nothing;`
  );
  for (const h of c.history || []) {
    if (!['tv_login', 'household_update'].includes(h.action)) continue;
    const status = ['success', 'failed', 'rate_limited', 'blocked'].includes(h.status) ? h.status : 'success';
    history.push({ mobile, ...h, status, accountId: accounts.some((a) => a.id === h.accountUsed) ? h.accountUsed : null });
  }
}
lines.push('');

for (const h of history) {
  lines.push(
    `insert into public.activations (subscriber_id, mobile, action, code, ip, status, account_id, notes, created_at)` +
      ` select s.id, s.mobile, ${q(h.action)}, ${q(h.code)}, ${q(h.ip)}, ${q(h.status)}, ${q(h.accountId)}, ${q(h.notes)}, ${q(h.date)}` +
      ` from public.subscribers s where s.mobile = ${q(h.mobile)}` +
      ` and not exists (select 1 from public.activations a where a.mobile = s.mobile and a.action = ${q(h.action)} and a.created_at = ${q(h.date)}::timestamptz);`
  );
}

lines.push(
  '',
  'commit;',
  '',
  "select 'subscribers' as table_name, count(*) as rows from public.subscribers",
  "union all select 'cookie_pool', count(*) from public.cookie_pool",
  "union all select 'activations', count(*) from public.activations",
  "union all select 'app_settings', count(*) from public.app_settings;",
  ''
);

const seedSql = lines.join('\n');
fs.writeFileSync(path.join(root, 'supabase', 'seed.local.sql'), seedSql);

const migration = fs.readFileSync(migrationPath, 'utf8');
fs.writeFileSync(
  path.join(root, 'supabase', 'RUN_ONCE.local.sql'),
  `-- Paste this whole file into Supabase > SQL Editor and click Run.\n-- Part 1: schema migration. Part 2: one-time customer seed.\n\n${migration}\n\n${seedSql}`
);

console.log(
  `Seed: ${seen.size} customers, ${accounts.length} account shell(s), ${history.length} history row(s); ${skipped} skipped (invalid or duplicate mobile).`
);
console.log('Wrote supabase/seed.local.sql and supabase/RUN_ONCE.local.sql');
